import { Router } from 'express';
import mongoose from 'mongoose';
import { Student, Enquiry, Payment, Mark } from '../models/school.js';
import ParentLink from '../models/ParentLink.js';
import { clean, yy, escapeRegex, nextNumber, peekNumber } from '../utils/helpers.js';
import { allowRoles } from '../middleware/auth.js';

const r = Router();
const validId = (id) => mongoose.isValidObjectId(id);

// Fields a teacher may change. Keep in sync with TEACHER_FIELDS in StudentProfile.jsx.
const TEACHER_EDITABLE = ['phone', 'altPhone', 'email', 'fatherName', 'motherName', 'fatherOccupation'];

r.get('/next-number', allowRoles('admin'), async (req, res) => {
  const n = await peekNumber(`adm-${yy()}`);
  res.json({ admNo: `ADM-${yy()}-${n}` });
});

// Reads: every logged-in staff role
r.get('/', async (req, res) => {
  const { q, class: cls, status } = req.query;
  const filter = {};
  if (cls) filter.class = cls;
  if (status) filter.status = status;
  if (q) {
    const rx = new RegExp(escapeRegex(q), 'i');
    filter.$or = [{ name: rx }, { admNo: rx }];
  }
  res.json(await Student.find(filter).sort({ admNo: 1 }));
});

r.get('/:id', async (req, res) => {
  if (!validId(req.params.id)) return res.status(404).json({ message: 'Student not found' });
  const doc = await Student.findById(req.params.id);
  doc ? res.json(doc) : res.status(404).json({ message: 'Student not found' });
});

// Create: admin only (superadmin always passes)
r.post('/', allowRoles('admin'), async (req, res) => {
  const body = clean(req.body);
  delete body.admNo; // always generated by the server
  const admNo = `ADM-${yy()}-${await nextNumber(`adm-${yy()}`)}`;
  const student = await Student.create({ ...body, admNo });
  if (body.enquiryFormNo) {
    await Enquiry.updateOne({ formNo: body.enquiryFormNo }, { status: 'Admitted' });
  }
  res.status(201).json(student);
});

// Edit a student. Empty values clear the field. The admission number can never change,
// because payments, marks and parent links all refer to it.
// Admin: every field. Teacher: contact and family details only.
r.patch('/:id', allowRoles('admin', 'teacher'), async (req, res) => {
  if (!validId(req.params.id)) return res.status(404).json({ message: 'Student not found' });

  let { admNo, _id, createdAt, updatedAt, __v, ...body } = req.body;

  if (req.user.role === 'teacher') {
    body = Object.fromEntries(Object.entries(body).filter(([key]) => TEACHER_EDITABLE.includes(key)));
    if (Object.keys(body).length === 0) {
      return res.status(403).json({ message: 'Teachers can only edit contact and family details' });
    }
  }

  const $set = {};
  const $unset = {};
  for (const [key, value] of Object.entries(body)) {
    if (value === '' || value == null) $unset[key] = '';
    else $set[key] = value;
  }
  if ('name' in $unset || 'class' in $unset || 'status' in $unset) {
    return res.status(400).json({ message: 'Name, class and status cannot be empty' });
  }

  const update = {};
  if (Object.keys($set).length) update.$set = $set;
  if (Object.keys($unset).length) update.$unset = $unset;

  const doc = await Student.findByIdAndUpdate(req.params.id, update, { new: true, runValidators: true });
  doc ? res.json(doc) : res.status(404).json({ message: 'Student not found' });
});

// Delete: admin only, and only for students with no money or marks records
r.delete('/:id', allowRoles('admin'), async (req, res) => {
  if (!validId(req.params.id)) return res.status(404).json({ message: 'Student not found' });
  const doc = await Student.findById(req.params.id);
  if (!doc) return res.status(404).json({ message: 'Student not found' });

  const [hasPayments, hasMarks] = await Promise.all([
    Payment.exists({ admNo: doc.admNo }),
    Mark.exists({ admNo: doc.admNo }),
  ]);
  if (hasPayments || hasMarks) {
    return res.status(409).json({
      message: 'This student has payment or marks records and cannot be deleted. Set their status to Transferred or Passed Out instead.',
    });
  }
  await ParentLink.deleteMany({ admNo: doc.admNo });
  await doc.deleteOne();
  res.json({ ok: true });
});

export default r;